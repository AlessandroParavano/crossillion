#!/usr/bin/env python3
"""
One command builds everything the game needs from the files in content/.

    python3 tools/build.py            build data/answers.js (downloads only what is new, then it is cached)
    python3 tools/build.py --check    only check the content files for mistakes (no network, writes nothing)
    python3 tools/build.py --offline  build using only cached downloads
    python3 tools/build.py --verses   draw a fresh random pool of ESV verses into data/verses.js

Pipeline:  content/*.txt -> Wikipedia article + 12 months of pageviews -> rank answers inside each question
           -> add the generated letter/fact questions -> data/answers.js
"""
import argparse, json, re, sys, unicodedata
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import content, derive, wiki   # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "answers.js"


def norm(s):
    s = "".join(c for c in unicodedata.normalize("NFD", s.lower()) if unicodedata.category(c) != "Mn")
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", " ", s)).strip()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--verses", action="store_true")
    args = ap.parse_args()

    if args.verses:
        import verses
        verses.build(ROOT / "data" / "verses.js")
        return

    cats, problems = content.load_questions()
    facts = content.load_facts()
    warns = content.check(cats, problems)
    n_entries = sum(len(c["entries"]) for c in cats)
    print(f"content: {len(cats)} questions, {n_entries} answers, {len(facts)} fact questions, "
          f"{sum(1 for c in cats if c['opts'].get('letters'))} questions take part in letter rules")
    for f in content.question_files():
        mine = [c for c in cats if c["file"] == f.name]
        print(f"  {f.name:<12} {len(mine):>3} questions  {sum(len(c['entries']) for c in mine):>5} answers")
    for w in warns:
        print("  !", w)
    if args.check:
        print("\nNo problems found." if not warns else f"\n{len(warns)} thing(s) to look at (the build still works).")
        return

    # ---- Wikipedia: resolve articles, then pageviews
    w = wiki.Wiki(offline=args.offline)
    print(f"pageview window: {w.start} to {w.end}")
    resolved = w.resolve([e["article"] for c in cats for e in c["entries"]])
    good = {}
    for c in cats:
        for e in c["entries"]:
            final, missing, disamb = resolved.get(e["article"], (e["article"], True, False))
            e["final"], e["bad"] = final, ("missing" if missing else "disambiguation" if disamb else None)
            if not e["bad"]:
                good[final] = None
    views = w.views(list(good))

    # ---- rank the answers inside each question
    dropped, out_cats = [], []
    for c in cats:
        seen, kept = {}, []
        for e in c["entries"]:
            v = views.get(e["final"])
            if e["bad"] or v is None:
                dropped.append(f"{c['id']}: \"{e['name']}\" -> {e['article']} ({e['bad'] or 'no data'})")
                continue
            if e["final"] in seen:                      # two names for the same article: keep one, merge the aliases
                seen[e["final"]]["aliases"] += [e["name"]] + e["aliases"]
                continue
            e["v"] = v
            seen[e["final"]] = e
            kept.append(e)
        kept.sort(key=lambda e: -e["v"])
        entries = []
        for rank, e in enumerate(kept, 1):
            forms = {norm(e["name"]), norm(e["final"]), norm(re.sub(r"\(.*?\)", "", e["final"]))} | {norm(a) for a in e["aliases"]}
            forms.discard("")
            entries.append({"n": e["name"], "w": e["final"].replace(" ", "_"), "v": e["v"], "r": rank, "a": sorted(forms)})
        if len(entries) < 15:
            print(f"  ! [{c['id']}] has only {len(entries)} usable answers - left out")
            continue
        out_cats.append({"id": c["id"], "prompt": c["prompt"], "total": len(entries), "entries": entries, "opts": c["opts"]})

    # ---- generated questions
    cfg = content.load_constraints()
    generated = derive.generate_rules(out_cats, cfg) + derive.generate_facts(out_cats, facts)
    for c in out_cats:
        c.pop("opts")

    data = {"generated": date.today().isoformat(), "window": [str(w.start), str(w.end)],
            "source": "Wikimedia REST API - human pageviews, en.wikipedia.org", "categories": out_cats + generated}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("/* GENERATED by tools/build.py from content/ - do not edit by hand. */\n"
                   "window.CROSSILLION_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    total = sum(c["total"] for c in data["categories"])
    print(f"\nWrote data/answers.js: {len(out_cats)} plain + {len(generated)} generated = {len(data['categories'])} questions, {total} answers")
    if dropped:
        print(f"\n{len(dropped)} answer(s) dropped (no matching Wikipedia article):")
        print("\n".join("  " + d for d in dropped))


if __name__ == "__main__":
    main()
